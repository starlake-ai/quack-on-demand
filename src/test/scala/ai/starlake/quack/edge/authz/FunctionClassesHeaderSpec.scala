package ai.starlake.quack.edge.authz

import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}
import java.util.Locale
import scala.jdk.CollectionConverters.*

/** Pins `native/qod-node/src/function_classes.inc`, the function classes qod-node's parse screen
  * judges calls by (CONTRACT Addendum 4 item 9), to the bundled `authz/function-classes.tsv` the
  * manager decides by, so the two cannot disagree: the header holds exactly the table's functions
  * and classes, one entry per line, sorted. It is generated by
  * `scripts/dev/gen-qod-node-function-classes.py`.
  */
class FunctionClassesHeaderSpec extends AnyFlatSpec with Matchers:

  private val Header     = Paths.get("native/qod-node/src/function_classes.inc")
  private val Regenerate =
    "the header is stale: run `python3 scripts/dev/gen-qod-node-function-classes.py`, then rebuild " +
      "qod-node"

  private val Entry =
    """QOD_FUNCTION_CLASS\("((?:[^"\\]|\\.)*)", "([^"]*)", "([^"]*)", "([^"]*)"\)""".r

  private def unescape(s: String): String = s.replace("\\\"", "\"").replace("\\\\", "\\")

  /** The header's entries in file order, as (name, schema, type, class). */
  private lazy val entries: List[(String, String, String, String)] =
    Files
      .readAllLines(Header, StandardCharsets.UTF_8)
      .asScala
      .toList
      .filterNot(l => l.isEmpty || l.startsWith("//"))
      .map {
        case Entry(name, schema, tpe, cls) => (unescape(name), schema, tpe, cls)
        case other => fail(s"unexpected line in $Header: $other. $Regenerate")
      }

  "the parse screen's function classes" should "be exactly the bundled table's" in {
    val header = entries.map { case (name, schema, tpe, cls) =>
      FunctionClasses.Key(schema, name, tpe) -> cls
    }.toMap
    val table = FunctionClasses.all.map { case (key, cls) =>
      key -> cls.toString.toLowerCase(Locale.ROOT)
    }
    withClue(s"$Regenerate. ") {
      header.keySet -- table.keySet shouldBe empty
      table.keySet -- header.keySet shouldBe empty
      header.filter { case (k, c) => table(k) != c } shouldBe empty
    }
  }

  it should "hold one entry per function, sorted by name, schema and type" in {
    val keys = entries.map { case (name, schema, tpe, _) => List(name, schema, tpe) }
    withClue(s"$Regenerate. ") {
      keys.distinct shouldBe keys
      // The generator writes printable ASCII only, where String order is byte order.
      keys.flatten.forall(_.forall(c => c >= ' ' && c <= '~')) shouldBe true
      keys shouldBe keys.sorted(using Ordering.Implicits.seqOrdering[List, String])
    }
  }

  it should "be lower case, as the screen compares names" in
    entries.foreach { case (name, schema, tpe, cls) =>
      withClue(s"$Regenerate. ") {
        name shouldBe name.toLowerCase(Locale.ROOT)
        schema shouldBe schema.toLowerCase(Locale.ROOT)
        Set(tpe, cls).foreach(c => c shouldBe c.toLowerCase(Locale.ROOT))
      }
    }

  it should "classify the functions the review's reproductions call" in {
    val byName = entries.groupBy(_._1).view.mapValues(_.map(_._4).toSet).toMap
    byName("setval") shouldBe Set("superuser")
    byName("current_setting") shouldBe Set("superuser")
    byName("nextval") shouldBe Set("allowed")
    byName("currval") shouldBe Set("allowed")
    byName("range") shouldBe Set("allowed")
    byName("upper") shouldBe Set("allowed")
  }
