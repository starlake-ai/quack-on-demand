#!/usr/bin/env python3
"""Generates native/qod-node/src/function_classes.inc from src/main/resources/authz/function-classes.tsv:
one QOD_FUNCTION_CLASS(name, schema, type, class) line per classified function, sorted by name, schema
and type (byte order), so the node's parse screen judges a call by the same classes the manager's
decision pipeline does (spec Section 6, CONTRACT Addendum 4 item 9). The parse screen refuses a
superuser-class function anywhere in a non-superuser's statement, and anything not classed allowed in
the slots DuckDB evaluates while binding. Built-in macros and table macros are listed too (types
`macro` and `table_macro`, classed from their bodies, Task 19): DuckDB expands them before any plan
exists, so only the screen judges them by class.

It also writes native/qod-node/src/builtin_macros.inc from native/qod-node/macros.json: one
QOD_BUILTIN_MACRO(name) line per built-in macro or table macro name, sorted. The screen refuses a call
to a name no classification lists, anywhere (CONTRACT Addendum 4 item 30); a built-in macro the TSV
does not class (its body is not all allowed) is known all the same, judged by its expansion outside
the bind-time slots and refused inside them.

Run it after every regeneration of the TSV (scripts/dev/gen-qod-node-classification.sh runs it last),
then rebuild qod-node and run `sbt "testOnly *FunctionClassesHeaderSpec"`, which fails while either
header is stale.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TSV = REPO / "src/main/resources/authz/function-classes.tsv"
OUT = REPO / "native/qod-node/src/function_classes.inc"
MACROS = REPO / "native/qod-node/macros.json"
MACROS_OUT = REPO / "native/qod-node/src/builtin_macros.inc"

TYPES = {"scalar", "aggregate", "window", "table", "pragma", "macro", "table_macro"}
CLASSES = {"allowed", "listing", "file", "superuser"}


def fail(message):
    sys.exit(f"gen-qod-node-function-classes: {message}")


def c_string(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    if any(ord(c) < 0x20 or ord(c) > 0x7E for c in escaped):
        fail(f"function name {text!r} is not printable ASCII")
    return f'"{escaped}"'


def main():
    rows = []
    seen = set()
    for number, line in enumerate(TSV.read_text(encoding="utf-8").splitlines(), start=1):
        if not line or line.startswith("#"):
            continue
        cells = line.split("\t")
        if len(cells) != 4:
            fail(f"{TSV.name} line {number}: expected 4 cells, got {len(cells)}")
        name, schema, tpe, cls = (cell.lower() for cell in cells)
        if tpe not in TYPES:
            fail(f"{TSV.name} line {number}: unknown function type {tpe}")
        if cls not in CLASSES:
            fail(f"{TSV.name} line {number}: unknown class {cls}")
        key = (name, schema, tpe)
        if key in seen:
            fail(f"{TSV.name} line {number}: {name} ({schema}, {tpe}) is classified twice")
        seen.add(key)
        rows.append((name, schema, tpe, cls))
    rows.sort(key=lambda row: tuple(cell.encode("utf-8") for cell in row[:3]))
    lines = [
        "// GENERATED by scripts/dev/gen-qod-node-function-classes.py from"
        " src/main/resources/authz/function-classes.tsv; do not edit.",
        "// Regenerate: python3 scripts/dev/gen-qod-node-function-classes.py",
        "// QOD_FUNCTION_CLASS(name, schema, type, class), lower case, sorted by name, schema and type.",
    ]
    lines += [f"QOD_FUNCTION_CLASS({', '.join(c_string(cell) for cell in row)})" for row in rows]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen-qod-node-function-classes: wrote {len(rows)} functions to {OUT.relative_to(REPO)}")
    macros = sorted({entry["name"].lower() for entry in json.loads(MACROS.read_text(encoding="utf-8"))},
                    key=lambda name: name.encode("utf-8"))
    lines = [
        "// GENERATED by scripts/dev/gen-qod-node-function-classes.py from native/qod-node/macros.json;"
        " do not edit.",
        "// Regenerate: python3 scripts/dev/gen-qod-node-function-classes.py",
        "// QOD_BUILTIN_MACRO(name): every built-in macro and table macro name, lower case, sorted.",
    ]
    lines += [f"QOD_BUILTIN_MACRO({c_string(name)})" for name in macros]
    MACROS_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen-qod-node-function-classes: wrote {len(macros)} macros to {MACROS_OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
